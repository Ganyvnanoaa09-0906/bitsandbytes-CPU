def main() -> int:
    # ---- 1. CLI: add three sections before "kernels" ----
    cli = io.open(CLI, encoding='utf-8').read()
    anchor = '    ("kernels", "Fused kernels (call them directly)", ['
    if cli.count(anchor) != 1:
        print('ABORT: kernels anchor %d' % cli.count(anchor))
        return 1
    cli = cli.replace(anchor, NEW_SECTIONS + anchor, 1)
    io.open(CLI, 'w', encoding='utf-8', newline='').write(cli)
    print('ok    CLI: igpu + quant23 + avx512 sections')

    # ---- 2. regenerate the two API reference files from the CLI itself ----
    env = dict(os.environ, PYTHONIOENCODING='utf-8')
    r = subprocess.run([sys.executable, 'bitsandbytes_cpu_cli.py', 'help', '--markdown'],
                       cwd=REPO, capture_output=True, text=True, encoding='utf-8', env=env)
    if r.returncode != 0 or not r.stdout.startswith('# CPU fork reference'):
        print('ABORT: CLI markdown generation failed: %s' % r.stderr[:400])
        return 1
    body = r.stdout
    cn_header = ('<!-- 本文件由 `bitsandbytes-cpu help --markdown` 生成,请勿手改;'
                 '要改内容请改 bitsandbytes_cpu_cli.py。 -->\n')
    io.open(os.path.join(DOCS, 'API_REFERENCE.md'), 'w', encoding='utf-8', newline='').write(cn_header + body)
    io.open(os.path.join(DOCS, 'API_REFERENCE_EN.md'), 'w', encoding='utf-8', newline='').write(body)
    for probe in ('iGPU acceleration (OpenCL/CLBlast', '2-bit and 3-bit quantisation',
                  'AVX-512 builds (experimental'):
        print('      generated contains %-42s %s' % (probe, probe in body))

    # ---- 3. MOTION_BOUNDARY: fix the dangling reference, add the English twin ----
    mb = io.open(os.path.join(DOCS, 'MOTION_BOUNDARY.md'), encoding='utf-8').read()
    if mb.count(MOTION_REF_OLD) != 1:
        print('ABORT: MOTION ref anchor %d' % mb.count(MOTION_REF_OLD))
        return 1
    mb = mb.replace(MOTION_REF_OLD, MOTION_REF_NEW, 1)
    io.open(os.path.join(DOCS, 'MOTION_BOUNDARY.md'), 'w', encoding='utf-8', newline='').write(mb)
    io.open(os.path.join(DOCS, 'MOTION_BOUNDARY_EN.md'), 'w', encoding='utf-8', newline='').write(MOTION_EN)
    print('ok    MOTION_BOUNDARY.md reference fixed, MOTION_BOUNDARY_EN.md written')

    # ---- 4. mirror the shipped docs into the root docs_cpu/ ----
    names = ['QUICKSTART.md', 'QUICKSTART_EN.md', 'TECHNICAL_GUIDE.md', 'TECHNICAL_GUIDE_EN.md',
             'TECH_REPORT.md', 'TECH_REPORT_EN.md', 'API_REFERENCE.md', 'API_REFERENCE_EN.md',
             'MOTION_BOUNDARY.md', 'MOTION_BOUNDARY_EN.md']
    for n in names:
        data = io.open(os.path.join(DOCS, n), 'rb').read()
        io.open(os.path.join(ROOT, n), 'wb').write(data)
    print('ok    root docs_cpu/ mirrored (%d files)' % len(names))
    return 0


if __name__ == '__main__':
    sys.exit(main())
